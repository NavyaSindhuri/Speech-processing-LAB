import numpy as np

def rms_energy(signal):
    return np.sqrt(np.mean(signal**2))

def zero_crossing_rate(signal):
    return np.mean(np.abs(np.diff(np.sign(signal)))) / 2

def periodicity_estimate(signal):
    autocorr = np.correlate(signal, signal, mode='full')
    autocorr = autocorr[len(autocorr)//2:]
    peaks = np.where((autocorr[1:-1] > autocorr[:-2]) & (autocorr[1:-1] > autocorr[2:]))[0]
    return len(peaks)

voiced_energy = rms_energy(voiced)
unvoiced_energy = rms_energy(unvoiced)

voiced_zcr = zero_crossing_rate(voiced)
unvoiced_zcr = zero_crossing_rate(unvoiced)

voiced_periodicity = periodicity_estimate(voiced)
unvoiced_periodicity = periodicity_estimate(unvoiced)

print("---- VOICED vs UNVOICED PHONEME ANALYSIS ----\n")

print(f"Voiced phoneme RMS energy: {voiced_energy:.4f}")
print(f"Unvoiced phoneme RMS energy: {unvoiced_energy:.4f}\n")

if voiced_energy > unvoiced_energy:
    print("Inference: The voiced phoneme exhibits higher energy, indicating strong vocal fold vibration.")
else:
    print("Inference: The unvoiced phoneme shows comparable energy, which is atypical for unvoiced sounds.")

print()

print(f"Voiced phoneme Zero Crossing Rate: {voiced_zcr:.4f}")
print(f"Unvoiced phoneme Zero Crossing Rate: {unvoiced_zcr:.4f}\n")

if voiced_zcr < unvoiced_zcr:
    print("Inference: Lower zero crossing rate in voiced phoneme indicates periodic structure.")
    print("Inference: Higher zero crossing rate in unvoiced phoneme indicates noise-like behavior.")
else:
    print("Inference: Zero crossing trends do not follow typical voiced-unvoiced behavior.")

print()

print(f"Estimated periodic peaks (Voiced): {voiced_periodicity}")
print(f"Estimated periodic peaks (Unvoiced): {unvoiced_periodicity}\n")

if voiced_periodicity > unvoiced_periodicity:
    print("Inference: Voiced phoneme shows clear periodicity due to vocal fold vibration.")
    print("Inference: Unvoiced phoneme lacks periodicity, confirming absence of voicing.")
else:
    print("Inference: Periodicity pattern is weak, possibly due to short segment length.")

fric_energy = rms_energy(fricative)
app_energy = rms_energy(approximant)

fric_zcr = zero_crossing_rate(fricative)
app_zcr = zero_crossing_rate(approximant)

fric_periodicity = periodicity_estimate(fricative)
app_periodicity = periodicity_estimate(approximant)

print("\n---- FRICATIVE vs APPROXIMANT ANALYSIS ----\n")

print(f"Fricative RMS energy: {fric_energy:.4f}")
print(f"Approximant RMS energy: {app_energy:.4f}\n")

print(f"Fricative Zero Crossing Rate: {fric_zcr:.4f}")
print(f"Approximant Zero Crossing Rate: {app_zcr:.4f}\n")

if fric_zcr > app_zcr:
    print("Inference: Fricative exhibits high zero crossing rate, indicating turbulent airflow.")
    print("Inference: Approximant exhibits smoother waveform with lower turbulence.")
else:
    print("Inference: Zero crossing behavior is inconclusive.")

print()

print(f"Fricative periodicity estimate: {fric_periodicity}")
print(f"Approximant periodicity estimate: {app_periodicity}\n")

if app_periodicity > fric_periodicity:
    print("Inference: Approximant shows periodic structure due to partial vocal fold vibration.")
    print("Inference: Fricative lacks periodicity due to constricted airflow.")
else:
    print("Inference: Periodicity contrast is weak, possibly due to articulation variation.")

print()

