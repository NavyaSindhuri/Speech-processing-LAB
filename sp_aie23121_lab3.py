import librosa
import numpy as np
import matplotlib.pyplot as plt
import torch
from transformers import Wav2Vec2Processor, Wav2Vec2ForCTC

processor = Wav2Vec2Processor.from_pretrained("facebook/wav2vec2-base-960h")
model = Wav2Vec2ForCTC.from_pretrained("facebook/wav2vec2-base-960h")
model.eval()

audio_path = "/content/lab3_sentence1.wav"

signal, sr = librosa.load(audio_path, sr=16000, mono=True)

duration = len(signal) / sr
print("Duration:", duration, "seconds")

plt.figure(figsize=(12,4))
plt.plot(signal)
plt.title("Speech Waveform")
plt.xlabel("Samples")
plt.ylabel("Amplitude")
plt.show()

inputs = processor(signal, sampling_rate=16000, return_tensors="pt")

with torch.no_grad():
    logits = model(inputs.input_values).logits

pred_ids = torch.argmax(logits, dim=-1)
tokens = processor.batch_decode(pred_ids)[0]

print("Recognized tokens:")
print(tokens)

num_tokens = len(tokens.replace(" ", ""))
segment_duration = duration / num_tokens

segments = []
start = 0

for i, ch in enumerate(tokens.replace(" ", "")):
    end = start + segment_duration
    s_idx = int(start * sr)
    e_idx = int(end * sr)
    segments.append((ch, signal[s_idx:e_idx]))
    start = end

for i, (ph, seg) in enumerate(segments[:8]):
    plt.figure(figsize=(4,2))
    plt.plot(seg)
    plt.title(f"Phoneme {i+1}: {ph}")
    plt.xlabel("Samples")
    plt.ylabel("Amplitude")
    plt.show()

voiced = segments[2][1]      # vowel-like
unvoiced = segments[6][1]    # fricative-like

plt.figure(figsize=(10,3))
plt.subplot(1,2,1)
plt.plot(voiced)
plt.title("Voiced Phoneme")

plt.subplot(1,2,2)
plt.plot(unvoiced)
plt.title("Unvoiced Phoneme")
plt.show()

